function readStored() {
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    return DICTIONARY[saved] ? saved : null;
  } catch (error) {
    // Private mode or blocked storage: fall back to the default, never throw.
    return null;
  }
}

let current = readStored() || DEFAULT_LANGUAGE;

const listeners = new Set();

export function getLanguage() {
  return current;
}

/*
  Resolution order: current language, then the other language, then the key.
  A key that reaches the caller unchanged is a visible, obvious gap rather
  than an empty control.
*/
export function t(key, params) {
  const value =
    (DICTIONARY[current] && DICTIONARY[current][key]) ??
    (DICTIONARY[current === "id" ? "en" : "id"] || {})[key] ??
    key;

  if (!params) {
    return value;
  }

  return String(value).replace(/\{(\w+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match
  );
}

export function setLanguage(code) {
  if (!DICTIONARY[code] || code === current) {
    return;
  }

  current = code;

  try {
    window.localStorage.setItem(STORAGE_KEY, code);
  } catch (error) {
    // Preference simply will not persist; the switch still works this session.
  }

  document.documentElement.setAttribute("lang", code);
  applyStaticTranslations();

  listeners.forEach(listener => {
    try {
      listener(code);
    } catch (error) {
      console.error(error);
    }
  });
}

export function onLanguageChange(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

/*
  Rewrites any statically authored markup that carries a data-i18n hook.
  Text is written with textContent, so a dictionary entry can never be
  interpreted as markup.
*/
export function applyStaticTranslations(root) {
  const scope = root || document;

  scope.querySelectorAll("[data-i18n]").forEach(node => {
    node.textContent = t(node.dataset.i18n);
  });

  scope.querySelectorAll("[data-i18n-placeholder]").forEach(node => {
    node.setAttribute("placeholder", t(node.dataset.i18nPlaceholder));
  });

  scope.querySelectorAll("[data-i18n-aria-label]").forEach(node => {
    node.setAttribute("aria-label", t(node.dataset.i18nAriaLabel));
  });
}

/*
  Compact ID | EN control. Used on the login screen and in the Admin header,
  so the language can be changed before signing in and afterwards without
  signing in again.
*/
export function createLanguageSwitch(className) {
  const wrap = document.createElement("div");
  wrap.className = className || "lang-switch";
  wrap.setAttribute("role", "group");
  wrap.setAttribute("aria-label", t("common.language"));

  const buttons = LANGUAGES.map(language => {
    const button = document.createElement("button");
    button.type = "button";
    button.className = "lang-switch-option";
    button.textContent = language.label;
    button.dataset.lang = language.code;
    button.title = language.name;
    button.addEventListener("click", () => setLanguage(language.code));
    wrap.appendChild(button);
    return button;
  });

  function sync() {
    buttons.forEach(button => {
      const active = button.dataset.lang === current;
      button.classList.toggle("is-active", active);
      button.setAttribute("aria-pressed", active ? "true" : "false");
    });

    wrap.setAttribute("aria-label", t("common.language"));
  }

  sync();
  onLanguageChange(sync);

  return wrap;
}

