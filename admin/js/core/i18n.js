/*
  Admin-only bilingual layer (Bahasa Indonesia + English).

  SCOPE
  -----
  Interface chrome only: labels, buttons, help text, dialogs, toasts,
  validation and status wording. It never touches content the owner wrote —
  a project title, a certificate name or a technology called "React.js" is
  stored data and is rendered exactly as saved, in either language.

  The public portfolio is not involved. Nothing here loads on index.html.

  HOW MODULES USE IT
  ------------------
  One import and one function:

      import { t } from "../../core/i18n.js";
      t("common.save")
      t("certificates.minimumHint", { count: 3 })

  Modules never branch on the current language. There is no
  `if (lang === "id")` anywhere; a missing translation falls back to the
  other language and then to the key itself, so a gap shows up as an
  obvious untranslated string rather than a blank button.

  STATIC MARKUP
  -------------
  admin/index.html marks its text with data-i18n / data-i18n-placeholder /
  data-i18n-aria-label, and applyStaticTranslations() rewrites it in place.
  That keeps the login and MFA screens translatable without turning their
  markup into JavaScript.

  PERSISTENCE
  -----------
  localStorage only. No database column, no user metadata, no server round
  trip — the preference is a property of this browser, and it survives sign
  out because it is not part of the session.
*/

